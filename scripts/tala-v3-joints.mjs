// Turns art/blender/tala-v3/joints.json (from the Blender joints mode) into the game's rig constants.
import {readFileSync,writeFileSync} from 'node:fs';
const data=JSON.parse(readFileSync(new URL('../art/blender/tala-v3/joints.json',import.meta.url),'utf8'));
const out=`// Generated by scripts/tala-v3-joints.mjs from art/blender/tala-v3/joints.json. Do not edit by hand.
export const talaV3Joints=${JSON.stringify(data.joints)};
export const talaV3Metrics=${JSON.stringify({legLength:data.legLength,shinLength:data.shinLength,ankleHeight:data.ankleHeight,gameHeight:data.game_height,scale:data.scale})};
`;
writeFileSync(new URL('../dist/tala-v3-joints.js',import.meta.url),out);console.log('Wrote dist/tala-v3-joints.js');
